// builds public/data/japan.js : an SVG path of Japan plus a projection helper
const fs = require('fs');
const topo = require('topojson-client');
const world = require('world-atlas/countries-50m.json');

const countries = topo.feature(world, world.objects.countries);
const japan = countries.features.find(f => f.id === '392');

// bounding box we care about (main islands + Okinawa-ish)
const LON0 = 128.5, LON1 = 146.5, LAT0 = 30.0, LAT1 = 45.8;
const W = 600;
const k = Math.cos((38 * Math.PI) / 180);
const H = Math.round((W * (LAT1 - LAT0)) / ((LON1 - LON0) * k));
const px = lon => ((lon - LON0) / (LON1 - LON0)) * W;
const py = lat => ((LAT1 - lat) / (LAT1 - LAT0)) * H;

function ringArea(r) {
  let a = 0;
  for (let i = 0; i < r.length - 1; i++) a += r[i][0] * r[i + 1][1] - r[i + 1][0] * r[i][1];
  return Math.abs(a / 2);
}

let d = '';
const polys = japan.geometry.type === 'Polygon' ? [japan.geometry.coordinates] : japan.geometry.coordinates;
for (const poly of polys) {
  const outer = poly[0];
  if (ringArea(outer) < 0.02) continue; // skip tiny islands
  const inBox = outer.some(([lo, la]) => lo > LON0 && lo < LON1 && la > LAT0 && la < LAT1);
  if (!inBox) continue;
  d += 'M' + outer.map(([lo, la]) => px(lo).toFixed(1) + ',' + py(la).toFixed(1)).join('L') + 'Z';
}

const out = `// generated by scripts/make-japan-svg.js from world-atlas (Natural Earth)
export const JAPAN = { w: ${W}, h: ${H}, d: ${JSON.stringify(d)} };
export function project(lat, lon) {
  return { x: ((lon - ${LON0}) / ${LON1 - LON0}) * ${W}, y: ((${LAT1} - lat) / ${(LAT1 - LAT0).toFixed(1)}) * ${H} };
}
`;
fs.writeFileSync(__dirname + '/../public/data/japan.js', out);
console.log('ok', W, H, d.length, 'chars');
